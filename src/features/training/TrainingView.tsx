import { useState } from 'react';
import { generateScenario, type Scenario } from './scenario';
import { ModeBadge } from '../../ui/ModeBadge';

const ENVS = ['Alpine trail, cold and windy', 'Desert canyon, midday heat', 'Forest service road, logging crew', 'Rural utility line crew', 'Winter backcountry ski tour'];
const FOCI = ['Severe bleeding', 'Signs of shock', 'Hypothermia', 'Heat illness', 'Suspected fracture', 'Burns', 'Multiple patients'];

export function TrainingView() {
  const [env, setEnv] = useState(ENVS[0]);
  const [focus, setFocus] = useState(FOCI[0]);
  const [difficulty, setDifficulty] = useState('intermediate');
  const [busy, setBusy] = useState(false);
  const [stream, setStream] = useState('');
  const [scenario, setScenario] = useState<{ s: Scenario; where: 'on_device' | 'in_cloud' } | null>(null);
  const [err, setErr] = useState<string | null>(null);

  const go = async () => {
    setBusy(true);
    setErr(null);
    setScenario(null);
    setStream('');
    const res = await generateScenario({ environment: env, focus, difficulty }, setStream);
    if (res.ok) setScenario({ s: res.scenario, where: res.served });
    else setErr(res.reason);
    setBusy(false);
  };

  return (
    <section className="panel training" aria-label="Training mode">
      <h2>Training Mode</h2>
      <p className="hint">
        Generate fictional drill scenarios for team training nights. No patient data is involved, so this <strong>prefers the cloud</strong>{' '}
        (falls back to on-device when offline).
      </p>
      <div className="form-grid">
        <label>
          Environment
          <select value={env} onChange={(e) => setEnv(e.target.value)}>
            {ENVS.map((x) => <option key={x}>{x}</option>)}
          </select>
        </label>
        <label>
          Focus
          <select value={focus} onChange={(e) => setFocus(e.target.value)}>
            {FOCI.map((x) => <option key={x}>{x}</option>)}
          </select>
        </label>
        <label>
          Difficulty
          <select value={difficulty} onChange={(e) => setDifficulty(e.target.value)}>
            <option>beginner</option>
            <option>intermediate</option>
            <option>advanced</option>
          </select>
        </label>
      </div>
      <button className="btn btn-primary btn-big" onClick={go} disabled={busy} data-testid="gen-scenario">
        {busy ? 'Generating…' : '🎲 Generate drill scenario'}
      </button>
      {busy && stream && <pre className="json stream">{stream}</pre>}
      {err && <div className="notice notice-warn">{err}</div>}
      {scenario && (
        <article className="doc ai-block" data-testid="scenario">
          <div className="report-head">
            <h3>{scenario.s.title}</h3>
            <ModeBadge where={scenario.where} />
          </div>
          <p><strong>Setting:</strong> {scenario.s.setting}</p>
          <p><strong>Patient (fictional):</strong> {scenario.s.patient}</p>
          <p><strong>Mechanism:</strong> {scenario.s.mechanism}</p>
          <h4>Presentation</h4>
          <ul>{scenario.s.presentation.map((x, i) => <li key={i}>{x}</li>)}</ul>
          <h4>Vitals progression (for the instructor)</h4>
          <ul>{scenario.s.vitalsProgression.map((v, i) => <li key={i}>T+{v.minute} min: {v.vitals}</li>)}</ul>
          <h4>Complications to inject</h4>
          <ul>{scenario.s.complications.map((x, i) => <li key={i}>{x}</li>)}</ul>
          <h4>Debrief questions</h4>
          <ul>{scenario.s.debriefQuestions.map((x, i) => <li key={i}>{x}</li>)}</ul>
          <p className="fineprint">Fictional training content generated by AI. Use your team's protocols for care decisions.</p>
        </article>
      )}
    </section>
  );
}
