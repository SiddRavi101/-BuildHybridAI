import type { Incident } from '../incident/db';
import type { Field, Item, ReportState } from '../report/schema';
import { hhmm } from '../report/rules';

export interface DocSection {
  heading: string;
  lines: string[];
}
export interface ExportDoc {
  title: string;
  subtitle: string;
  banner: string;
  sections: DocSection[];
  footer: string;
}

const val = (f: Field) => (f.value ? f.value + (f.status === 'draft' ? ' [unconfirmed]' : '') : '—');
const mark = <T,>(i: Item<T>) => (i.status === 'draft' ? ' [unconfirmed]' : '');

export function countUnconfirmed(r: ReportState): number {
  const fields = [r.patient.ageRange, r.patient.sex, r.patient.chiefComplaint, r.mechanismOfInjury, r.handoffNotes];
  return (
    fields.filter((f) => f.status === 'draft').length +
    [...r.injuries, ...r.interventions, ...r.vitals].filter((i) => i.status === 'draft').length
  );
}

export function vitalsLine(v: { time: string; hr?: number | null; rr?: number | null; bp?: string; spo2?: number | null; gcs?: number | null; temp?: number | null }) {
  const parts = [
    v.hr != null && `HR ${v.hr}`,
    v.rr != null && `RR ${v.rr}`,
    v.bp && `BP ${v.bp}`,
    v.spo2 != null && `SpO2 ${v.spo2}%`,
    v.gcs != null && `GCS ${v.gcs}`,
    v.temp != null && `Temp ${v.temp}`,
  ].filter(Boolean);
  return `${v.time || '--:--'}  ${parts.join(' · ') || '(no values)'}`;
}

/** MIST: Mechanism, Injuries, Signs (vitals), Treatment. Template-only — no AI needed. */
export function buildMist(inc: Incident): ExportDoc {
  const r = inc.report;
  const unconfirmed = countUnconfirmed(r);
  return {
    title: 'MIST Handoff',
    subtitle: `Incident ${inc.title} · started ${new Date(inc.startedAt).toLocaleString()}${inc.endedAt ? ` · handoff ${hhmm(new Date(inc.endedAt))}` : ''}`,
    banner:
      unconfirmed > 0
        ? `${unconfirmed} item(s) are AI/auto drafts not yet confirmed by the responder — marked [unconfirmed].`
        : 'All items confirmed by the responder.',
    sections: [
      {
        heading: 'Patient',
        lines: [`Age range: ${val(r.patient.ageRange)}`, `Sex: ${val(r.patient.sex)}`, `Chief complaint: ${val(r.patient.chiefComplaint)}`],
      },
      { heading: 'M — Mechanism of injury', lines: [val(r.mechanismOfInjury)] },
      {
        heading: 'I — Injuries observed',
        lines: r.injuries.length
          ? r.injuries.map((i) => `${[i.data.side, i.data.bodyRegion].filter(Boolean).join(' ')}: ${i.data.type}${i.data.notes ? ` (${i.data.notes})` : ''}${mark(i)}`)
          : ['None recorded'],
      },
      { heading: 'S — Signs / vitals', lines: r.vitals.length ? r.vitals.map((v) => vitalsLine(v.data) + mark(v)) : ['None recorded'] },
      {
        heading: 'T — Treatment given',
        lines: r.interventions.length
          ? r.interventions.map((i) => `${i.data.time || '--:--'}  ${i.data.type}${i.data.notes ? ` (${i.data.notes})` : ''}${mark(i)}`)
          : ['None recorded'],
      },
      ...(inc.protocols.length
        ? [{ heading: 'Protocol cards used', lines: inc.protocols.map((p) => `${p.protocolId} (${p.checked.length} steps checked)`) }]
        : []),
      ...(r.handoffNotes.value ? [{ heading: 'Notes', lines: [val(r.handoffNotes)] }] : []),
    ],
    footer: 'Generated by Pinpoint Field. Record of what the responder reported; not a diagnosis.',
  };
}

export function docToText(d: ExportDoc): string {
  return [
    d.title.toUpperCase(),
    d.subtitle,
    `! ${d.banner}`,
    '',
    ...d.sections.flatMap((s) => [s.heading, ...s.lines.map((l) => `  ${l}`), '']),
    d.footer,
  ].join('\n');
}
